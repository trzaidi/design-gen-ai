import Image from "next/image";
import { SiteHeader } from "@/components/site-header";
import { SiteFooter } from "@/components/site-footer";
import { createClient } from "@/lib/supabase/server";
import { MEME_IMAGES } from "@/lib/meme-images";

export const metadata = { title: "Credits | Caption Archive" };

export default async function CreditsPage() {
  const supabase = await createClient();
  const { data } = await supabase.auth.getClaims();
  const claims = data?.claims;
  const signedIn = Boolean(claims?.sub) && !claims?.is_anonymous;
  return <div className="page">
    <SiteHeader signedIn={signedIn} email={typeof claims?.email === "string" ? claims.email : undefined} />
    <main className="interior-page" id="main">
      <p className="eyebrow">Image credits</p>
      <h1 className="interior-title">CREDITS<span className="period">.</span></h1>
      <p className="panel-copy">Campus photos are freely licensed from Wikimedia Commons and used with attribution; the scenes and captions written over them are parody. Captions are generated by Google Gemini. Columbia University does not endorse this student project.</p>
      <ul className="credit-list">
        {MEME_IMAGES.map((image) => <li key={image.path}>
          <Image src={image.path} alt="" width={image.width} height={image.height} sizes="8rem" />
          <div><strong>{image.title}</strong><span>{image.source}</span>
            {"sourceUrl" in image ? <a href={image.sourceUrl} target="_blank" rel="noopener noreferrer">View source and license →</a> : null}</div>
        </li>)}
      </ul>
    </main>
    <SiteFooter />
  </div>;
}
